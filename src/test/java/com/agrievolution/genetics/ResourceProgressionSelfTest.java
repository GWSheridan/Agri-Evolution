    private static void field(CropSpecies a, CropSpecies b, CropSpecies result, int chance) {
        var recipe = SpeciesBreeder.mutationRecipe(a, b);
        if (recipe == null || recipe.offspring() != result || recipe.baseChance() != chance
                || SpeciesBreeder.mutationRecipe(b, a).offspring() != result)
            throw new AssertionError("Wrong field recipe " + result);
        int n=0;
        for (int s=0;s<10000;s++) {
            var out=SpeciesBreeder.cross(a,b,s);
            if (out==result) n++;
            else if(out!=a && out!=b) throw new AssertionError("Wrong field offspring " + out);
            if ((SpeciesBreeder.cross(b,a,s)==result) != (out==result))
                throw new AssertionError("Field cross asymmetry");
        }
        if (Math.abs(n - chance*100) > 300) throw new AssertionError("Field odds " + result+": "+n);
    }
    private static void lab(CropSpecies a, CropSpecies b, CropSpecies result, int chance) {
        if(SpeciesBreeder.mutationRecipe(a,b)!=null)throw new AssertionError("Laboratory recipe available in field");
        var recipe=AdvancedHybridBreeder.recipe(a,b);
        if (recipe==null || recipe.offspring()!=result || recipe.baseChance()!=chance
                || AdvancedHybridBreeder.recipe(b,a).offspring()!=result
                || recipe.chance(true,true)!=chance+13)
            throw new AssertionError("Wrong Tier 3 recipe " + result);
        int n=0;
        for(int s=0;s<10000;s++) {
            var out=AdvancedHybridBreeder.crossSpecies(a,b,s,false,false);
            if(out==result)n++;
            else if(out!=a && out!=b)throw new AssertionError("Wrong Tier 3 offspring");
            if((AdvancedHybridBreeder.crossSpecies(b,a,s,false,false)==result)!=(out==result))
                throw new AssertionError("Tier 3 asymmetry");
        }
        if(Math.abs(n-chance*100)>300)throw new AssertionError("Tier 3 odds " + result+": "+n);
    }
